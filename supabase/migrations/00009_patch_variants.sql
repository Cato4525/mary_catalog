-- ============================================================
-- PHASE 12: Validation
-- ============================================================

DO $$
DECLARE
  total_products bigint;
  total_variants bigint;
  total_images bigint;
  images_with_variant bigint;
  products_without_variant bigint;
BEGIN
  SELECT count(*) INTO total_products FROM public.products;
  SELECT count(*) INTO total_variants FROM public.product_variants;
  SELECT count(*) INTO total_images FROM public.product_images;
  SELECT count(*) INTO images_with_variant
    FROM public.product_images WHERE variant_id IS NOT NULL;
  SELECT count(*) INTO products_without_variant
    FROM public.products p
    WHERE NOT EXISTS (
      SELECT 1 FROM public.product_variants pv WHERE pv.product_id = p.id
    );

  RAISE NOTICE '=== Migration 00009 Validation ===';
  RAISE NOTICE 'Products: %', total_products;
  RAISE NOTICE 'Variants: %', total_variants;
  RAISE NOTICE 'Images: %', total_images;
  RAISE NOTICE 'Images with variant_id: %', images_with_variant;
  RAISE NOTICE 'Products without variant: %', products_without_variant;

  IF products_without_variant > 0 THEN
    RAISE WARNING '% products have no variant!', products_without_variant;
  END IF;

  IF images_with_variant != total_images THEN
    RAISE WARNING '% of % images missing variant_id!',
      total_images - images_with_variant, total_images;
  END IF;

  IF total_variants < total_products THEN
    RAISE WARNING 'More products (%) than variants (%) — expected equal.',
      total_products, total_variants;
  END IF;
END $$;
