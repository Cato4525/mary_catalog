-- ============================================================
-- PHASE 4: Create product_variants for every existing product
--           One variant per product, using its color text.
--           No new rows in products.
-- ============================================================

DO $$
DECLARE
  prod RECORD;
  color_id_val bigint;
  variant_id_val bigint;
  has_color_col boolean;
BEGIN
  -- Check if products.color column exists
  SELECT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'products' AND column_name = 'color'
  ) INTO has_color_col;

  FOR prod IN
    SELECT p.id, p.color, p.disponible
    FROM public.products p
    WHERE NOT EXISTS (
      SELECT 1 FROM public.product_variants pv
      WHERE pv.product_id = p.id
    )
  LOOP
    -- Find or create the color row
    IF has_color_col AND prod.color IS NOT NULL AND TRIM(prod.color) != '' THEN
      SELECT id INTO color_id_val
      FROM public.colors
      WHERE nombre = TRIM(prod.color)
      LIMIT 1;

      IF color_id_val IS NULL THEN
        INSERT INTO public.colors (nombre, codigo_hex)
        VALUES (TRIM(prod.color), '#808080')
        ON CONFLICT (nombre) DO NOTHING;
        SELECT id INTO color_id_val
        FROM public.colors
        WHERE nombre = TRIM(prod.color)
        LIMIT 1;
      END IF;
    ELSE
      -- No color text: use "Sin color"
      SELECT id INTO color_id_val
      FROM public.colors
      WHERE nombre = 'Sin color'
      LIMIT 1;
    END IF;

    -- Create the variant
    INSERT INTO public.product_variants (product_id, color_id, activo)
    VALUES (prod.id, color_id_val, COALESCE(prod.disponible, true))
    RETURNING id INTO variant_id_val;

    -- Link this product's images to the new variant
    UPDATE public.product_images
    SET variant_id = variant_id_val
    WHERE product_id = prod.id
      AND (variant_id IS NULL OR variant_id != variant_id_val);
  END LOOP;
END $$;

-- ============================================================
-- PHASE 5: Make variant_id NOT NULL on product_images
--           Only after Phase 4 linked all images.
-- ============================================================

-- Verify no orphan images remain
DO $$
DECLARE
  orphans bigint;
BEGIN
  SELECT count(*) INTO orphans
  FROM public.product_images
  WHERE variant_id IS NULL;

  IF orphans > 0 THEN
    RAISE EXCEPTION 'Migration aborted: % product_images have no variant_id. Fix data before proceeding.', orphans;
  END IF;
END $$;

-- Safe to enforce NOT NULL now
ALTER TABLE public.product_images
  ALTER COLUMN variant_id SET NOT NULL;

-- ============================================================
-- PHASE 6: Add FK constraint from product_images → product_variants
-- ============================================================

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM information_schema.table_constraints tc
    JOIN information_schema.constraint_column_usage ccu
      ON tc.constraint_name = ccu.constraint_name
    WHERE tc.constraint_type = 'FOREIGN KEY'
      AND tc.table_name = 'product_images'
      AND ccu.column_name = 'variant_id'
      AND ccu.table_name = 'product_variants'
  ) THEN
    ALTER TABLE public.product_images
      ADD CONSTRAINT product_images_variant_id_fkey
      FOREIGN KEY (variant_id) REFERENCES public.product_variants(id)
      ON DELETE CASCADE;
  END IF;
END $$;

